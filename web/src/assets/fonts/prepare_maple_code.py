"""Create the code webfonts and matching unicode-range CSS from the pinned upstream TTF."""

import argparse
from concurrent.futures import ProcessPoolExecutor
from hashlib import sha256
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

SOURCE_SHA256 = '8cec0b9c25139a75d4fb02b0690fc2fe970ecd3bae7b69451edc53627256897f'
HAN_RANGES = ((0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x323AF))
HAN_CHUNK_SIZE = 384


def is_han(codepoint):
    return any(start <= codepoint <= end for start, end in HAN_RANGES)


def css_ranges(codepoints):
    ranges = []
    for codepoint in codepoints:
        if ranges and ranges[-1][1] == codepoint - 1:
            ranges[-1][1] = codepoint
        else:
            ranges.append([codepoint, codepoint])
    return ', '.join(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}' for start, end in ranges)


def cmap_tables(font):
    return {(table.platformID, table.platEncID, table.format): table.cmap for table in font['cmap'].tables}


def create_shard(source, output, name, codepoints):
    options = subset.Options(
        flavor='woff2', name_IDs=['*'], name_languages=['*'], recalc_timestamp=False,
    )
    options.drop_tables.append('meta')
    font = subset.load_font(source, options)
    original_tables = {key: cmap.copy() for key, cmap in cmap_tables(font).items()}
    original_metrics = font['hmtx'].metrics.copy()
    selection = subset.Subsetter(options=options)
    selection.populate(unicodes=codepoints)
    selection.subset(font)
    filename = f'maple-code-{name}.woff2'
    destination = output / filename
    subset.save_font(font, destination, options)

    expected = {
        key: {cp: cmap[cp] for cp in codepoints if cp in cmap}
        for key, cmap in original_tables.items()
    }
    with TTFont(destination) as saved:
        actual = cmap_tables(saved)
        if set().union(*actual.values()) != set(codepoints):
            raise ValueError(f'{filename}: cmap coverage differs from its assigned range')
        saved_metrics = saved['hmtx'].metrics
        # The subset may rename glyphs. Verify each platform's mappings,
        # including aliases, and compare horizontal advances and bearings.
        glyph_names = {}
        for key, expected_cmap in expected.items():
            # FontTools removes the Windows full-Unicode table when it only
            # repeats the retained Windows BMP table.
            fallback = actual.get((3, 1, 4), {}) if key == (3, 10, 12) else {}
            saved_cmap = actual.get(key, fallback)
            if expected_cmap.keys() != saved_cmap.keys():
                raise ValueError(f'{filename}: cmap coverage differs for {key}')
            for cp, original in expected_cmap.items():
                current = saved_cmap[cp]
                if glyph_names.setdefault(original, current) != current or original_metrics[original] != saved_metrics[current]:
                    raise ValueError(f'{filename}: mapping or metrics changed for U+{cp:X}')
        if len(set(glyph_names.values())) != len(glyph_names):
            raise ValueError(f'{filename}: distinct glyphs were merged')

    css = (
        '@font-face {\n'
        '    font-family: "HAPI Code Mono";\n'
        f'    src: url("./{filename}") format("woff2");\n'
        '    font-style: normal;\n'
        '    font-weight: 400;\n'
        '    font-display: swap;\n'
        f'    unicode-range: {css_ranges(codepoints)};\n'
        '}\n'
    )
    return css, destination.stat().st_size


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='MapleMonoNormalNL-CN-Regular.ttf from the pinned release')
    parser.add_argument('--output', type=Path, default=Path(__file__).with_name('maple-code'))
    args = parser.parse_args()
    if sha256(args.source.read_bytes()).hexdigest() != SOURCE_SHA256:
        parser.error('the source does not match the pinned Maple Mono 7.9 Regular TTF')

    with TTFont(args.source) as font:
        codepoints = sorted(set().union(*cmap_tables(font).values()))
    han = [cp for cp in codepoints if is_han(cp)]
    shards = [('base', [cp for cp in codepoints if not is_han(cp)])]
    shards.extend(
        (f'han-{index + 1:02d}', han[offset:offset + HAN_CHUNK_SIZE])
        for index, offset in enumerate(range(0, len(han), HAN_CHUNK_SIZE))
    )
    args.output.mkdir(parents=True, exist_ok=True)
    with ProcessPoolExecutor(max_workers=4) as pool:
        pending = [
            pool.submit(create_shard, args.source, args.output, name, chunk)
            for name, chunk in shards
        ]
        generated = [task.result() for task in pending]

    css = '/* Generated by prepare_maple_code.py. */\n\n' + '\n'.join(rule for rule, _ in generated)
    (args.output / 'maple-code.css').write_text(css, encoding='utf-8', newline='\n')
    sizes = [size for _, size in generated]
    print(f'{len(shards)} shards, {len(codepoints)} code points, {sum(sizes):,} bytes')
    print(f'Base: {sizes[0]:,} bytes. Han: {min(sizes[1:]):,}–{max(sizes[1:]):,} bytes per shard.')


if __name__ == '__main__':
    main()
